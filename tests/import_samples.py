def rpd_docx(merged: bool = True) -> bytes:
    """РПД: титул, таблица «компетенция – индикаторы» (ячейка компетенции объединена по
    вертикали на все её индикаторы) и упоминание кодов в тексте без формулировок."""
    doc = Document()
    doc.add_paragraph("МИНИСТЕРСТВО НАУКИ И ВЫСШЕГО ОБРАЗОВАНИЯ РОССИЙСКОЙ ФЕДЕРАЦИИ")
    doc.add_paragraph("РАБОЧАЯ ПРОГРАММА ДИСЦИПЛИНЫ (МОДУЛЯ)")
    doc.add_paragraph("Рабочая программа дисциплины «Базы данных»")
    doc.add_paragraph("Направление подготовки 09.03.04 Программная инженерия")
    doc.add_paragraph("1. Перечень планируемых результатов обучения по дисциплине")
    rows = sum(len(inds) for _, inds in RPD_COMPETENCIES) + 1
    table = doc.add_table(rows=rows, cols=2)
    table.cell(0, 0).text = "Код и наименование компетенции"
    table.cell(0, 1).text = "Код и наименование индикатора достижения компетенции"
    r = 1
    for competency, indicators in RPD_COMPETENCIES:
        first = table.cell(r, 0)
        first.text = competency
        for ind in indicators:
            table.cell(r, 1).text = ind
            r += 1
        if merged and len(indicators) > 1:
            first.merge(table.cell(r - 1, 0))
            first.text = competency
    doc.add_paragraph("")
    doc.add_paragraph("Дисциплина участвует в формировании компетенций ОПК-2, ПК-1.")
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


